export function getTranslation(lang: Language, key: string, values?: TranslationValues): string {
  const template = translations[lang]?.[key] ?? translations["vi"]?.[key] ?? key;
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}

export function translateBookingStatus(status: string, lang: Language): string {
  return getTranslation(lang, `status.${status}`);
}
